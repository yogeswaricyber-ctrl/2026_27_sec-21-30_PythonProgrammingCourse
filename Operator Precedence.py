# Demonstrating Operator Precedence

result1 = 10 + 5 * 2
print("10 + 5 * 2 =", result1)

result2 = (10 + 5) * 2
print("(10 + 5) * 2 =", result2)

# Demonstrating Associativity

result3 = 20 - 10 - 5
print("20 - 10 - 5 =", result3)

result4 = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", result4)