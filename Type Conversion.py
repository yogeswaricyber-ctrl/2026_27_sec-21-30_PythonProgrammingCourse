# Demonstrating Type Conversion

num1 = "10"
num2 = "5.5"

# String to Integer
a = int(num1)
print("String to Integer:", a)
print("Type:", type(a))

# String to Float
b = float(num2)
print("String to Float:", b)
print("Type:", type(b))

# Integer to String
c = str(a)
print("Integer to String:", c)
print("Type:", type(c))